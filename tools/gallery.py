#!/usr/bin/env python3
"""A route's gallery list: every CG its script shows, in story order (first appearance).

    python3 tools/gallery.py redlightning

Reads game/<route>/*.rpy for `show cg <name>` and vn_enter(..., cg="<name>") and writes
game/<route>/gallery.rpy, registering the list with the catalog's gallery (game/catalog/vn.rpy
vn_register_gallery). Re-run after adding pictures to a route's script.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
# the order the route's files are read in: the story's order (the hand-written scenes are
# reached from the passages, so they slot in where their passage jumps to them)
FILES = {"redlightning": ["script.rpy", "encounters.rpy"], "hypno": ["script.rpy", "hub.rpy", "encounters.rpy"]}
PREFIX = {"redlightning": "rl_", "hypno": "hy_"}
# the route's Ren'Py walk traces (tools/rptest.sh outputs)
TRACES = {"redlightning": "renpy-?.jsonl", "hypno": "renpy-hy-*.jsonl"}


def main():
    route = sys.argv[1] if len(sys.argv) > 1 else "redlightning"
    d = ROOT / "game" / route
    # a route not listed above (the rewrites after hypno): its script then its written-out scenes,
    # and the label prefix of its first label (co_opening -> "co_")
    if route not in FILES:
        FILES[route] = [f for f in ("script.rpy", "scenes.rpy", "acts.rpy", "encounters.rpy") if (d / f).exists()]
        first = re.search(r"^label ([a-z]+_)", (d / FILES[route][0]).read_text(), flags=re.M)
        PREFIX[route] = first.group(1)
        TRACES[route] = f"renpy-{route}*.jsonl"
    pre = PREFIX[route]
    pat = re.compile(r'show cg (' + pre + r'[a-z0-9_]+)|cg="(' + pre + r'[a-z0-9_]+)"')
    texts = {f: (d / f).read_text() for f in FILES[route]}
    order = []
    # the passages in order; a passage that jumps to a written-out scene takes that scene's
    # pictures at the jump
    enc = texts.get("encounters.rpy", "")
    scenes = {m.group(1): m.start() for m in re.finditer(r"^label (\w+):", enc, flags=re.M)}

    def pictures_of(text):
        return [a or b for a, b in pat.findall(text)]

    def scene_text(label):
        start = scenes[label]
        nxt = min([p for p in scenes.values() if p > start] or [len(enc)])
        return enc[start:nxt]

    body = "\n".join(texts[f] for f in FILES[route] if f != "encounters.rpy")
    for line in body.splitlines():
        for name in pictures_of(line):
            if name not in order:
                order.append(name)
        m = re.search(r"jump (\w+_sex)\b", line)
        if m and m.group(1) in scenes:
            for name in pictures_of(scene_text(m.group(1))):
                if name not in order:
                    order.append(name)
    # story order: when each picture first comes up in the test walks (trace/renpy-*.jsonl,
    # tools/rptest.sh); walk b's own pictures go in after the picture before them there;
    # pictures no walk reaches (the free-play door scenes) keep their file order at the end
    walks = []
    trace_glob = TRACES[route]
    for f in sorted((ROOT / "trace").glob(trace_glob)):
        seen = []
        for line in f.read_text().splitlines():
            cg = __import__("json").loads(line).get("cg")
            if cg and cg not in seen:
                seen.append(cg)
        walks.append(seen)
    if walks:
        story = list(walks[0])
        for w in walks[1:]:
            for i, name in enumerate(w):
                if name not in story:
                    before = next((w[j] for j in range(i - 1, -1, -1) if w[j] in story), None)
                    story.insert(story.index(before) + 1 if before else 0, name)
        order = [n for n in story if n in order] + [n for n in order if n not in story]
    out = d / "gallery.rpy"
    out.write_text("## GENERATED by tools/gallery.py: the route's pictures in story order, for the gallery.\n"
                   "## Re-run the tool after adding pictures; don't edit.\n\n"
                   f"init 10 python:\n    vn_register_gallery({route!r}, [\n"
                   + "".join(f"        {n!r},\n" for n in order) + "    ])\n")
    print(f"wrote {out.relative_to(ROOT)}: {len(order)} pictures")


if __name__ == "__main__":
    main()
