def label_of(title):
    if title in R["skip"]:
        raise ConvertError(f"link to a passage outside the pilot: {title!r}")
    return R["label"] + re.sub(r"[^a-z0-9]+", "_", title[len(R["prefix"]):].lower()).strip("_")


def parse(title, body):
    root = []
    stack = [("block", root)]
    st = {"growth": 0, "loc": None, "fx": [], "last": None}

    def cur():
        k, x = stack[-1]
        if k == "block":
            return x
        if k == "if":
            return x.branches[-1][1]
        if k == "switch":
            if not x.cases:
                raise ConvertError(f"{title}: text before the first <<case>>")
            return x.cases[-1][1]
        if k == "link":
            return x.body
        raise AssertionError(k)

    def add(node):
        cur().append(node)
        if isinstance(node, Say):
            if st["fx"]:
                node.fx, st["fx"] = st["fx"], []
            st["last"] = node
        elif not isinstance(node, (Comment, Stmt)):
            st["last"] = None

    def macro(tok):
        if DROP_RE.match(tok):
            return
        m = LOC_RE.match(tok)
        if m:
            st["loc"] = st["loc"] or m.group(1)
            return
        if MACROS.get(tok) is not None:
            v = MACROS[tok]
            code, eff = (v if isinstance(v, tuple) else (v, None))
            return add(Stmt(code, eff))
        for rx, kind in MACRO_RE:
            m = rx.match(tok)
            if m:
                return add(route_macro(kind, m))
        m = PASS_RE.match(tok)
        if m:
            return add(Stmt(f"$ vn_pass({m.group(1)})"))
        m = PASS_EXPR_RE.match(tok)
        if m:
            return add(Stmt(f"$ vn_pass({cond(m.group(1))})"))
        m = FEAT_RE.match(tok)
        if m:
            return add(Stmt(f'$ vn_feat("{m.group(1)}")'))
        m = HOME_RE.match(tok)
        if m:
            return add(Stmt(f'$ {R["state"]}.home = "{m.group(1)}"'))
        if tok in ("<<sl_growth>>", "<</sl_growth>>"):
            st["growth"] += 1 if tok == "<<sl_growth>>" else -1
            return
        m = re.match(r"^<<if (.+)>>$", tok)
        if m:
            node = If(cond(m.group(1)))
            add(node)
            stack.append(("if", node))
            return
        m = re.match(r"^<<elseif (.+)>>$", tok)
        if m:
            stack[-1][1].branches.append([cond(m.group(1)), []])
            return
        if tok == "<<else>>":
            stack[-1][1].branches.append([None, []])
            return
        if tok == "<</if>>":
            assert stack[-1][0] == "if", title
            stack.pop()
            st["last"] = None
            return
        m = re.match(r"^<<switch (.+)>>$", tok)
        if m:
            node = Switch(cond(m.group(1)))
            add(node)
            stack.append(("switch", node))
            return
        m = re.match(r"^<<case (.+)>>$", tok)
        if m:
            stack[-1][1].cases.append([m.group(1), []])
            return
        if tok == "<<default>>":
            stack[-1][1].cases.append([None, []])
            return
        if tok == "<</switch>>":
            assert stack[-1][0] == "switch", title
            stack.pop()
            st["last"] = None
            return
        m = re.match(r"^<<link \[\[(.+?)\|(.+?)\]\]>>$", tok)
        if m:
            lab, tgt = m.groups()
            node = Link(lab, tgt, dynamic=tgt.startswith("_"))
            add(node)
            stack.append(("link", node))
            return
        if tok == "<</link>>":
            assert stack[-1][0] == "link", title
            stack.pop()
            return
        m = re.match(r'^<<route_sleep "([^"]+)" (\d+)(?: "([^"]+)")?>>$', tok)
        if m:
            tgt, h, lab = m.groups()
            return add(Link(lab or "Sleep", tgt, pre=[Stmt(f"call vn_night({h})")]))
        m = re.match(r'^<<route_return "[^"]+">>$', tok)
        if m:
            return add(Link("Choose another story", "@" + R["return_label"]))
        if tok.startswith("<<route_leave "):
            # free play's way out: only ever in a branch that folds away (Route.running is true)
            return add(Stmt("UNREACHABLE " + tok, {"unreachable": True}))
        s = set_stmt(tok)
        if s:
            return add(s)
        raise ConvertError(f"{title}: unknown macro {tok!r}")

    lines = body.split("\n")
    in_comment, buf = False, []
    for raw in lines:
        line = raw.strip()
        if in_comment:
            buf.append(line)
            if "*/" in line:
                in_comment = False
                add(Comment(" ".join(buf)))
                buf = []
            continue
        if not line:
            continue
        if line.startswith("/*") and "*/" not in line:
            in_comment, buf = True, [line]
            continue
        if line.startswith("/*") and line.endswith("*/") and line.count("/*") == 1:
            add(Comment(line))
            continue
        line = re.sub(r"/\*[\s\S]*?\*/", "", line).strip()
        if not line:
            continue
        m = DIRECTIVE.match(line)
        if m:
            k, v = m.group(1), (m.group(2) or "").strip()
            if k in ("shake", "flash"):
                st["fx"].append(k)
            else:
                add(Stmt(directive(k, v), {"fit": v} if k == "outfit" and v != "auto" else None))
            continue
        if code_only(line):
            for tok in TOKEN.split(line):
                tok = tok.strip()
                if tok:
                    if not tok.startswith("<"):
                        raise ConvertError(f"{title}: stray text {tok!r} in {line!r}")
                    macro(tok)
            continue
        if line.startswith("+ ") and st["last"] is not None:
            prev = st["last"]
            text, _ = render(line[2:], prev.pre)
            if prev.kind == "sfx":
                prev.kind, prev.text = "narr", "{=vn_sfx_i}" + prev.text + "{/=vn_sfx_i} " + text
            else:
                prev.text += " " + text
            prev.plain += " " + line[2:]
            continue
        m = SPEAKER.match(line)
        if m and m.group(1) in R["speakers"]:
            who, face, rest = m.groups()
            pre = []
            text, plain = render(rest, pre)
            node = Say("say", text, who=who, growth=st["growth"] > 0)
            node.face, node.plain, node.pre = face, plain, pre
            add(node)
            continue
        pre = []
        if re.match(r"^~[^~]+~$", line):
            text, plain = render(line[1:-1], pre)
            node = Say("sfx", text)
        elif re.match(r"^\(.*\)$", line):
            text, plain = render(line, pre)
            node = Say("thought", text, growth=st["growth"] > 0)
        else:
            text, plain = render(line, pre)
            node = Say("narr", text, growth=st["growth"] > 0)
        node.face, node.plain, node.pre = None, plain, pre
        add(node)
    if len(stack) != 1:
        raise ConvertError(f"{title}: unclosed {stack[-1][0]}")
    return root, st["loc"]


def route_macro(kind, m):
    """A route's own macro forms (its config's MACRO_RE) -> a node."""
    g = m.groups()
    if kind == "rl_advance":
        return Stmt(f"$ rl_advance({g[1]})")
    if kind == "until":
        return Stmt(f"$ vn_until({g[1]})")
    if kind == "feel":
        return Feel()
    if kind == "onward":
        return Onward()
    if kind == "wake":
        return Wake()
    if kind == "rl_wait":
        return Link("[_rlS[1]]", "_rlS[0]", pre=[Stmt(f"$ vn_until({g[0]})")], dynamic=True)
    if kind == "hy_advance":
        return Stmt(f"$ hy_advance({g[1]})")
    if kind == "hy_until":
        return Stmt(f"$ hy_until({g[0]})")
    if kind == "hy_flav":
        return Stmt(f'$ hy.flav = "{g[0]}"')
    if kind == "hy_body":
        return Body(int(g[0]))
    if kind == "hy_induct":
        return Stmt("$ hy_induct()")
    if kind == "app_notify":
        # the phone's notification card, as a line: the app's name in gold over its message in pink
        pre = []
        body = render(g[1], pre)[0]
        node = Say("narr", "{color=#ffd700}" + render(g[0])[0] + "{/color}\\n{color=#e40081}" + body + "{/color}")
        node.plain, node.pre = g[0] + " " + re.sub(r"<[^>]+>", "", g[1]), pre
        return node
    if kind == "hy_route_end":
        return Stmt(f'$ hy.ending = "{g[0]}"')
    if kind == "route_return":
        return Link("Choose another story", "@" + R["return_label"])
    raise ConvertError(f"route macro kind {kind}")


def directive(k, v):
    a = v.split()
    art = R["art"]
    cast_tags = sorted({t for w, t in R["sprites"].items() if w not in R["pc_whos"]})
    if k == "bg":
        return "hide bg onlayer bgl" if v == "off" else f"show bg {art}{v.replace('-', '_')} onlayer bgl"
    if k == "cg":
        return "hide cg onlayer cgl" if v == "off" else f"show cg {art}{v.replace('-', '_')} onlayer cgl"
    if k == "pc":
        return f"show {R['pc_tag']} {v} at vn_pc_slot"
    if k == "outfit":
        return "pass" if v == "auto" else f'$ {R["state"]}.fit = "{v}"'
    if k == "in":
        tag = R["sprites"].get(a[0])
        if not tag:
            return "pass"
        others = [f"hide {t}" for t in cast_tags if t != tag]
        return "\n".join(others + [f"show {tag} {a[1] if len(a) > 1 else 'neutral'} at vn_cast_slot"])
    if k == "out":
        return "\n".join(f"hide {t}" for t in cast_tags) or "pass"
    if k == "face":
        tag = R["sprites"].get(a[0])
        if a[0] in R["pc_whos"]:
            return f"show {R['pc_tag']} {a[1]} at vn_pc_slot"
        return f'$ vn_face("{tag}", "{a[1]}")' if tag else "pass"
    raise ConvertError(f"directive @{k} {v}")


