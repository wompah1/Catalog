#!/usr/bin/env python3
"""twee (the DoL catalog's VN script) -> Ren'Py script, for one route: a ONE-TIME migration.

Once a route is converted its script.rpy is the source (owner, 2026-11-11) and this tool refuses
to overwrite it. Routes with no VN script yet are written straight in Ren'Py, not converted.

    python3 tools/twee2rpy.py redlightning

Reads the route's passages from catalog/game/02-engine/storylines/<route>/*.twee (the VN-script
format of framework/vn-script.js: @bg/@pc/@outfit/@in/@out/@face/@cg/@shake/@flash cues, `who
[face]: line` plates, ~SFX~, (thought), + join), its scene-art rows (scene-art.js), and the DoL
trace of the current VN screen (trace/<route>-*.json, tools/trace_dol.py), and writes
game/<route>/script.rpy: one label per passage.

Every macro is mapped explicitly (MACROS, set_stmt, cond); one it doesn't know is an error, never
a guess. What the DoL wardrobe decided implicitly (which outfit sprite set the PC wears on each
line) comes from the trace: the converter emits `$ rl.fit = ...` wherever the screen changed it.

A passage's links become a Ren'Py menu (two or more) or a lone way on (one): its label is shown
under the passage's last line, the way the VN screen joins a lone link to the last page.
"""
