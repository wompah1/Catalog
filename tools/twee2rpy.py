def configure(route):
    global R, ROWS, INLINE, INLINE_RE, MACROS, MACRO_RE, DROP_RE
    cfg = CONFIGS[route]
    R, ROWS, INLINE, MACROS = cfg["R"], cfg["ROWS"], cfg["INLINE"], cfg["MACROS"]
