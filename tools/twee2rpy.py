def load_fits():
    """From the DoL traces: (passage, plain line) -> {tier: outfit set} as the screen showed it, and
    passage -> {tier: the outfit its first sprite page showed} (where each visit opens)."""
    fits, starts = {}, {}
    pat = re.compile(rf"^pc-r\d(?:-([a-z]+))?-(?:{R['faces']})\.png$")
    for f in sorted((ROOT / "trace").glob(f"{R['id']}-*.json")):
        for p in json.loads(f.read_text()):
            first = True
            for pg in p["pages"]:
                spr = pg.get("pc") or pg.get("face")
                m = pat.match(spr or "")
                if not m:
                    continue
                fit = m.group(1)
                if fit and fit not in R["fits"]:
                    continue
                if first:
                    starts.setdefault(p["passage"], {}).setdefault(p["tier"], fit)
                    first = False
                for ln in pg["lines"]:
                    key = skel(ln["text"])
                    if len(key) >= 6:
                        fits.setdefault((p["passage"], key), {})[p["tier"]] = fit
    return fits, starts


def load_art():
    js = (R["dir"] / "scene-art.js").read_text()
    rows = re.findall(r'passage:\s*"((?:[^"\\]|\\.)*)",\s*at:\s*"((?:[^"\\]|\\.)*)",\s*img:\s*"([\w-]+)"', js)
    art = {}
    for passage, at, img in rows:
        art.setdefault(passage, []).append((at, img))
    return art


def passages():
    out = []
    for src in R["sources"]:
        text = (R["dir"] / src).read_text()
        for part in re.split(r"^:: ", text, flags=re.M)[1:]:
            head, _, body = part.partition("\n")
            m = re.match(r"^(.+?)(?:\s+\[([^\]]*)\])?\s*$", head)
            out.append((m.group(1).strip(), (m.group(2) or "").split(), body, src))
    return out


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    configure(args[0] if args else "redlightning")
    (fits, starts), art = load_fits(), load_art()
    out = list(R["header"]) + [""]
    n, warn = 0, []
    for title, tags, body, src in passages():
        if title in R["skip"] or title in R["handwritten"] or "widget" in tags:
            continue
        if "vn" not in tags:
            raise ConvertError(f"{title}: not a VN script passage and not skipped or handwritten")
        nodes, loc = parse(title, body)
        row = ROWS.get(title, {})
        e = Emitter(title, fits, art.get(title, []))
        e.w(0, f"label {label_of(title)}:")
        e.w(1, f"## {src}: :: {title} [{' '.join(tags)}]")
        # where each visit opens: the outfit the DoL screen's first sprite page showed, per rung
        st_ = R["state"]
        if row.get("outfit"):
            e.w(1, f'$ {st_}.fit = "{row["outfit"]}"')
            e.fit = row["outfit"]
        elif title in R["fit_fix"]:
            e.fit_before(1, Say("narr", ""))
        elif title in starts:
            st = starts[title]
            vals = set(st.values())
            if len(vals) == 1:
                want = next(iter(vals))
                e.w(1, f"$ {st_}.fit = {json.dumps(want)}" if want else f"$ {st_}.fit = None")
                e.fit = want
            else:
                m = ", ".join(f"{t}: {json.dumps(f) if f else 'None'}" for t, f in sorted(st.items()))
                e.w(1, f"$ {st_}.fit = {{{m}}}.get({st_}.tier, None)")
        bg = row.get("bg")
        bgx = f'"{R["art"]}{bg.replace("-", "_")}"' if bg else (R["default_bg"](loc) if loc and not row.get("cg") else "None")
        cast = row.get("cast", [])
        castx = cast if isinstance(cast, str) else "[" + ", ".join(f'("{t}", "{f}")' for t, f in cast) + "]"
        cgx = f'"{R["art"]}{row["cg"].replace("-", "_")}"' if row.get("cg") else "None"
        # the passage's opening code runs first (the landing, the rung, the kit), then the stage
        # comes up, as DoL renders a passage after its macros
        k = 0
        while k < len(nodes) and (isinstance(nodes[k], Comment) or (isinstance(nodes[k], Stmt) and nodes[k].code.startswith("$ ")
                                                                    and not nodes[k].code.startswith(f"$ {st_}.fit"))):
            k += 1
        e.block(nodes[:k], 1)
        e.w(1, f'$ vn_enter(bg={bgx}, pc="{row.get("pc", R["face"])}", pc_tag="{R["pc_tag"]}", cast={castx}, cg={cgx})')
        e.maybe = {t for t, f in cast} if not isinstance(cast, str) else set(e.cast_tags)
        e.block(nodes[k:], 1)
        if not terminal(nodes):
            warn.append(f"{title}: no way on at its end")
            e.w(1, "return")
        out += e.out + [""]
        n += 1
    outarg = next((a.split("=", 1)[1] for a in sys.argv if a.startswith("--out=")), None)
    dst = pathlib.Path(outarg) if outarg else ROOT / "game" / R["id"] / "script.rpy"
    if not outarg and dst.exists() and not dst.read_text().startswith("## GENERATED") and "--force" not in sys.argv:
        raise ConvertError(f"{dst.relative_to(ROOT)} is the route's source now (edited by hand); "
                           "not overwriting it. --force writes it anyway (and loses those edits).")
    dst.write_text("\n".join(out))
    print(f"wrote {dst}: {n} passages, {len(out)} lines")
    for w_ in warn:
        print("  WARN", w_)


def walk(nodes):
    for n in nodes:
        yield n
        if isinstance(n, If):
            for _, b in n.branches:
                yield from walk(b)
        elif isinstance(n, Switch):
            for _, b in n.cases:
                yield from walk(b)
        elif isinstance(n, Link):
            yield from walk(n.body)


if __name__ == "__main__":
    try:
        main()
    except ConvertError as ex:
        print("ERROR", ex)
        sys.exit(1)
