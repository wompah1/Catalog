ALLOWED = {"vn_clock", "True", "False", "not", "and", "or", "None", "max"}


def cond(js):
    s = js.strip()
    # DoL's worn-slot checks guard a <<generalWear>> the sprites never show (the sports bra, the
    # cycle shorts): always true, and their bodies drop
    s = re.sub(r'\$worn\.\w+\.name isnot "[^"]*"', "True", s)
    # DoL's hypnosis traits are its own mechanics (the trait lines don't port): their checks fold
    s = re.sub(r"\(\$hypnosis_traits\.\w+ \?\? 0\) lt \d+", "True", s)
    for a, b in R["cond"] + [("Time.hour", "vn_clock.hour"), ("Time.days", "vn_clock.day"),
                             ("Time.minute", "vn_clock.minute"), ("Route.running", "True")]:
        s = s.replace(a, b)
    for a, b in [(" isnot ", " != "), (" is ", " == "), (" gte ", " >= "), (" lte ", " <= "), (" lt ", " < "),
                 (" gt ", " > "), (" eq ", " == ")]:
        s = s.replace(a, b)
    s = re.sub(r"!(?!=)", "not ", s)
    s = re.sub(r"\btrue\b", "True", s)
    s = re.sub(r"\bfalse\b", "False", s)
    if re.match(r"^False and ", s):
        s = "False"
    # what's left must be names we know: the route state, the clock, the passage's temporaries
    names = re.findall(r'(?<![."\w])([A-Za-z_]\w*)', re.sub(r'"[^"]*"', '""', s))
    bad = [n for n in names if n not in ALLOWED | R["allowed"]]
    if bad or "$" in s or "?" in s:
        raise ConvertError(f"expression {js!r} -> {s!r}: unknown {bad}")
    return s


def set_stmt(tok):
    m = SET_RE.match(tok)
    if not m:
        return None
    lhs, rhs = m.groups()
    for a, b in R["set"]:
        lhs = lhs.replace(a, b)
    if not re.match(rf"^({R['state']}\.\w+|_{R['label'][:-1]}\w+|_hmCame)$", lhs):
        raise ConvertError(f"set target {tok!r}")
    lhs = R["set_rename"].get(lhs, lhs)
    return Stmt(f"$ {lhs} = {cond(rhs)}")


