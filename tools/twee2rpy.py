UNKNOWN = object()


class Emitter:
    def __init__(self, title, fits, art):
        self.title, self.fits, self.art = title, fits, art
        self.out = []
        self.fit = UNKNOWN
        self.warn = []
        # the cast sprites that could be on stage here (routes with more than one cast sprite only:
        # a hide is emitted only for one that could be showing)
        self.cast_tags = sorted({t for w, t in R["sprites"].items() if w not in R["pc_whos"]})
        self.track = len(self.cast_tags) > 1
        self.maybe = set()

    def w(self, ind, s):
        for part in s.split("\n"):
            if self.track:
                m = re.match(r"^(show|hide) (\w+)\b", part)
                if m and m.group(2) in self.cast_tags:
                    if m.group(1) == "hide":
                        if m.group(2) not in self.maybe:
                            continue
                        self.maybe.discard(m.group(2))
                    else:
                        self.maybe.add(m.group(2))
            self.out.append("    " * ind + part)

    def fit_before(self, ind, node):
        fix = R["fit_fix"].get(self.title)
        if fix is not None:
            for snip, want in fix:
                if (not snip and self.fit is UNKNOWN) or (snip and skel(snip) in skel(node.plain)):
                    if want != self.fit:
                        self.w(ind, f"$ {R['state']}.fit = {json.dumps(want)}" if want else f"$ {R['state']}.fit = None")
                        self.fit = want
            return
        seen = self.fits.get((self.title, skel(node.plain)))
        if not seen and "\x00" in node.plain:
            # a value worked out at show time (the clock): the trace line with the same text either side
            a, _, b = node.plain.partition("\x00")
            a, b = skel(a), skel(b)
            seen = next((v for (t, k), v in self.fits.items() if t == self.title and k.startswith(a) and k.endswith(b)
                         and len(k) > len(a) + len(b)), None)
        if not seen:
            return
        vals = set(seen.values())
        if len(vals) == 1:
            want = next(iter(vals))
            if want != self.fit:
                self.w(ind, f"$ {R['state']}.fit = {json.dumps(want)}" if want else f"$ {R['state']}.fit = None")
                self.fit = want
        else:
            m = ", ".join(f"{t}: {json.dumps(f) if f else 'None'}" for t, f in sorted(seen.items()))
            st = R["state"]
            self.w(ind, f"$ {st}.fit = {{{m}}}.get({st}.tier, {st}.fit)")
            self.fit = UNKNOWN

    def say(self, ind, node, caption=False):
        # the scene-art picture whose line this is (scene-art.js rows): the frame from here on
        for at, img in self.art:
            if skel(at) and skel(at) in skel(node.plain):
                self.w(ind, f"show cg {R['art']}sa_{img} onlayer cgl")
        self.fit_before(ind, node)
        for code in node.pre:
            self.w(ind, code)
        text = node.text
        if node.growth and node.kind != "sfx":
            text = "{color=" + GROWTH + "}" + text + "{/color}"
        if node.kind == "say":
            tag = R["sprites"].get(node.who)
            if node.face and tag:
                slot = "vn_pc_slot" if node.who in R["pc_whos"] else "vn_cast_slot"
                self.w(ind, f"show {tag} {node.face} at {slot}")
            who = R["speakers"][node.who] + " "
        else:
            who = {"narr": "", "thought": "vn_th ", "sfx": "vn_sfx "}[node.kind]
        fx = "" if caption or not node.fx else f' with vnfx({", ".join(json.dumps(x) for x in node.fx)})'
        return f'{who}"{text}"{fx}'

    def target(self, ln):
        t = ln.target
        if t.startswith("@"):
            return f"jump {t[1:]}"
        if ln.dynamic:
            return f"jump expression {t}"
        return f"jump {label_of(t)}"

    def link_label(self, ln):
        lab = ln.label
        if lab.startswith("[") and lab.endswith("]"):
            return lab   # an interpolation, e.g. [_rlS[1]]
        return render(lab)[0]

    def block(self, nodes, ind):
        if R.get("join_across"):
            nodes = flatten(nodes)
        i = 0
        while i < len(nodes):
            n = nodes[i]
            if isinstance(n, Link):
                j = i
                while j < len(nodes) and isinstance(nodes[j], (Link, Comment)):
                    j += 1
                links = [x for x in nodes[i:j] if isinstance(x, Link)]
                self.links(links, ind, nodes[:i])
                i = j
                continue
            if isinstance(n, Say):
                # a Say immediately followed (past statements) by links is the menu's caption
                k = i + 1
                while k < len(nodes) and (isinstance(nodes[k], (Stmt, Comment)) or (R.get("join_across") and silent(nodes[k]))):
                    k += 1
                if k < len(nodes) and isinstance(nodes[k], Onward):
                    for x in nodes[i + 1:k]:
                        self.node(x, ind)
                    self.onward(ind, n)
                    i = k + 1
                    continue
                if k < len(nodes) and isinstance(nodes[k], Link):
                    n.pending_caption = True
                    for x in nodes[i + 1:k]:
                        self.node(x, ind)
                    self.caption = n
                    i = k
                    continue
            self.node(n, ind)
            i += 1

    def links(self, links, ind, before):
        cap = getattr(self, "caption", None)
        self.caption = None
        if len(links) == 1:
            ln = links[0]
            if cap is not None:
                line = self.say(ind, cap)
                if ln.label not in ("Next", "Back"):
                    tail = "\\n{size=-5}{color=#ff8fa3}▸ " + self.link_label(ln) + "{/color}{/size}"
                    line = re.sub(r'"((?: with vnfx\(.*\))?)$', lambda m: tail + '"' + m.group(1), line)
                self.w(ind, line)
            elif ln.label not in ("Next", "Back"):
                self.w(ind, '"{size=-5}{color=#ff8fa3}▸ ' + self.link_label(ln) + '{/color}{/size}"')
            self.block(ln.body, ind)
            self.w(ind, self.target(ln))
            return
        # the caption's own statements (its picture, its outfit, its sprite) come before the menu
        line = self.say(ind, cap, caption=True) if cap is not None else None
        self.w(ind, "menu:")
        if line:
            self.w(ind + 1, line)
        before = set(self.maybe)
        for ln in links:
            self.maybe = set(before)
            self.w(ind + 1, f'"{self.link_label(ln)}":')
            self.block(ln.body, ind + 2)
            self.w(ind + 2, self.target(ln))

    def node(self, n, ind):
        if isinstance(n, Comment):
            self.out.append("    " * ind + "## " + re.sub(r"^/\*|\*/$", "", n.text).strip())
        elif isinstance(n, Stmt):
            if n.effect.get("unreachable"):
                raise ConvertError(f"{self.title}: emitted a free-play macro: {n.code}")
            self.w(ind, n.code)
            if "fit" in n.effect:
                self.fit = n.effect["fit"]
        elif isinstance(n, Say):
            self.w(ind, self.say(ind, n))
        elif isinstance(n, Feel):
            self.w(ind, "$ _rl_feel = rl_take_feel()")
            self.w(ind, "if _rl_feel:")
            self.w(ind + 1, '"{color=#e40081}[_rl_feel]{/color}"')
        elif isinstance(n, Wake):
            self.w(ind, "$ _rl_wake = rl_wake()")
            self.w(ind, '"[_rl_wake]"')
        elif isinstance(n, Onward):
            self.onward(ind, None)
        elif isinstance(n, Body):
            self.w(ind, f"$ _hy_sens = hy_body({n.n})")
            self.w(ind, "if _hy_sens:")
            self.w(ind + 1, '"{color=' + GROWTH + '}[_hy_sens]{/color}"')
        elif isinstance(n, Notify):
            pre = []
            body = render(n.body, pre)[0]
            for code in pre:
                self.w(ind, code)
            self.w(ind, '"{color=#ffd700}' + render(n.title)[0] + '{/color}\\n{color=#e40081}' + body + '{/color}"')
        elif False:
            self.w(ind, "$ _rlS = rl_straight()")
            self.w(ind, "if _rlS:")
            self.w(ind + 1, '"{size=-5}{color=#ff8fa3}▸ [_rlS[1]]{/color}{/size}"')
            self.w(ind + 1, "$ vn_until(14)")
            self.w(ind + 1, "jump expression _rlS[0]")
            self.w(ind, "else:")
            self.w(ind + 1, '"{size=-5}{color=#ff8fa3}▸ Down to the track{/color}{/size}"')
            self.w(ind + 1, "$ vn_pass(2)")
            self.w(ind + 1, "jump rl_hub")
        elif isinstance(n, If):
            self.branches(n.branches, ind)
        elif isinstance(n, Switch):
            br = [[(f"{n.expr} == {c}" if c is not None else None), body] for c, body in n.cases]
            self.branches(br, ind)
        else:
            raise AssertionError(type(n))

    def onward(self, ind, cap):
        """<<rl_onward>>: a morning's way on, joined to its last line (a lone link): straight to
        today's rung at the session, or down to the hub."""
        self.w(ind, "$ _rlS = rl_straight()")
        self.w(ind, '$ _rl_on = _rlS[1] if _rlS else "Down to the track"')
        tail = "\\n{size=-5}{color=#ff8fa3}▸ [_rl_on]{/color}{/size}"
        if cap is not None:
            line = self.say(ind, cap)
            self.w(ind, re.sub(r'"((?: with vnfx\(.*\))?)$', lambda m: tail + '"' + m.group(1), line))
        else:
            self.w(ind, '"' + tail[2:] + '"')
        self.w(ind, "if _rlS:")
        self.w(ind + 1, "$ vn_until(14)")
        self.w(ind + 1, "jump expression _rlS[0]")
        self.w(ind, "$ vn_pass(2)")
        self.w(ind, "jump rl_hub")

    def branches(self, branches, ind):
        # constant folding: Route.running is always true in the game (the route is running)
        branches = [b for b in branches if b[0] != "False"]
        if not branches:
            return
        for k, (c, body) in enumerate(branches):
            if c == "True":
                branches = branches[:k] + [[None, body]]
                break
        if branches[0][0] is None:
            self.block(branches[0][1], ind)
            return
        if all(not b for _, b in branches):
            return
        save, ends = self.fit, []
        save_maybe, maybe_after = set(self.maybe), set()
        for k, (c, body) in enumerate(branches):
            head = "if" if k == 0 else "elif" if c is not None else "else"
            self.w(ind, f"{head} {c}:" if c is not None else "else:")
            self.fit = save
            self.maybe = set(save_maybe)
            n0 = len(self.out)
            self.block(body, ind + 1)
            if len(self.out) == n0:
                self.w(ind + 1, "pass")
            ends.append(self.fit)
            maybe_after |= self.maybe
        if branches[-1][0] is not None:
            ends.append(save)   # no else: the outfit may be the one it came in with
            maybe_after |= save_maybe
        self.maybe = maybe_after
        # every way through leaves the same outfit: it's known after the block
        self.fit = ends[0] if all(e is not UNKNOWN and e == ends[0] for e in ends) else UNKNOWN


def live(branches):
    """A branch list with the always-false branches gone."""
    return [b for b in branches if b[0] != "False"]


def flatten(nodes):
    """Splice in the body of an If whose only live branch is always true (Route.running)."""
    out = []
    for n in nodes:
        if isinstance(n, If):
            br = live(n.branches)
            if br and br[0][0] == "True":
                out += flatten(br[0][1])
                continue
        out.append(n)
    return out


def silent(n):
    """Shows nothing and leaves nowhere: statements, comments, and branches made only of those."""
    if isinstance(n, (Stmt, Comment)):
        return True
    if isinstance(n, If):
        return all(all(silent(x) for x in body) for _, body in live(n.branches))
    if isinstance(n, Switch):
        return all(all(silent(x) for x in body) for _, body in n.cases)
    return False


def terminal(nodes):
    """Does this block always leave by a jump (a link, an onward, a branch that always does)?"""
    for n in reversed(nodes):
        if isinstance(n, Comment):
            continue
        if isinstance(n, (Link, Onward)):
            return True
        if isinstance(n, If):
            br = n.branches
            br = [b for b in br if b[0] != "False"]
            if not br:
                continue
            if any(c == "True" for c, _ in br):
                return terminal(next(b for c, b in br if c == "True"))
            return br[-1][0] is None and all(terminal(b) for _, b in br)
        if isinstance(n, Switch):
            return n.cases and n.cases[-1][0] is None and all(terminal(b) for _, b in n.cases)
        return False
    return False


